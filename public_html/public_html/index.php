Groene kunst? Natuur? Of ecologisch verantwoord schilderen? De verklaring is simpeler: mijn naam is Marjo <B>Groen</B>. Vandaar de naam van deze website.
<BR><BR>Toch is natuur wel degelijk een inspiratiebron voor mijn schilderijen. Zo schilder ik graag dieren en ook abstracte vormen, die ik vaak afleid van concrete natuurverschijnselen.
<BR><BR>Op de Vrije Academie in Zevenaar en later bij atelier "De Waan" heb ik leren tekenen, schilderen en etsen, met allerlei materialen zoals potlood, houtskool, krijt, inkt, aquarel-, olie- en acrylverf. Daarbij beoefende ik verschillende schildertechnieken, van realistisch tot abstract.
<BR><BR>Mijn zoektocht naar geliefde onderwerpen, kleurgebruik, stijl en materiaal heeft tot verschillende inzichten geleid. Zo brengen mijn kleurige schilderijen uit de beginperiode vrolijkheid en boeit mij momenteel de mysterieuze kant van de natuur. Het meer abstraheren nodigt mij uit tot "grasduinen" en telkens opnieuw en anders kijken.
<BR><BR>Ik schilder ook in opdracht. Hiervoor kunt u mij persoonlijk benaderen via mail of mobiel (zie Contact). 
<BR><BR>Veel kijkplezier! 
